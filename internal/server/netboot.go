// requiredNetbootAssets are the files a PXE session needs.
var requiredNetbootAssets = []string{
	"vmlinuz",
	"initrd.img",
	"grubnetx64.efi",
	"pxelinux.0",
	"ldlinux.c32",
}

// optionalNetbootAssets improve compatibility but are not fatal if missing.
var optionalNetbootAssets = []string{
	"libcom32.c32",
	"libutil.c32",
	"menu.c32",
	"grubx64.efi",
}

// prepareNetboot copies the shipped netboot assets into the runtime directory
// so that per-session configurations can be written next to them.
func (s *Server) prepareNetboot() {
	src := s.cfg.AssetsDir
	dst := filepath.Join(s.cfg.StateDir, "netboot")
	if err := os.MkdirAll(dst, 0o755); err != nil {
		s.Logf("netboot: cannot create %s: %v", dst, err)
		return
	}
	ok := true
	for _, name := range append(append([]string{}, requiredNetbootAssets...), optionalNetbootAssets...) {
		from := filepath.Join(src, name)
		to := filepath.Join(dst, name)
		if _, err := os.Stat(to); err == nil {
			continue
		}
		if _, err := os.Stat(from); err != nil {
			continue
		}
		if err := copyFile(from, to, 0o644); err != nil {
			s.Logf("netboot: copy %s failed: %v", name, err)
		}
	}
	for _, name := range requiredNetbootAssets {
		if _, err := os.Stat(filepath.Join(dst, name)); err != nil {
			ok = false
			s.Logf("netboot: missing required asset %s (looked in %s)", name, src)
		}
	}
	s.netboot = ok
	if ok {
		s.Logf("netboot: assets ready in %s", dst)
	}
}

// kernelCommandLine builds the cmdline handed to netbooted clients.
func (s *Server) kernelCommandLine(sess *Session) string {
	return fmt.Sprintf(
		"netclone.server=%s:%d netclone.token=%s netclone.policy=%s "+
			"console=tty0 console=ttyS0,115200 loglevel=4 quiet",
		sess.ServerIP, s.cfg.HTTPPort, sess.Token, sess.Policy)
}

// renderNetboot writes grub.cfg and pxelinux.cfg/default for the session.
func (s *Server) renderNetboot(sess *Session) error {
	root := filepath.Join(s.cfg.StateDir, "netboot")
	if err := os.MkdirAll(filepath.Join(root, "pxelinux.cfg"), 0o755); err != nil {
		return err
	}

	cmdline := s.kernelCommandLine(sess)
	grub := fmt.Sprintf(`set timeout=5
set default=0

menuentry "NetClone - imaj dagitimi" {
    linux (tftp)/vmlinuz %s
    initrd (tftp)/initrd.img
}
`, cmdline)

	pxe := fmt.Sprintf(`DEFAULT netclone
PROMPT 0
TIMEOUT 50

LABEL netclone
    KERNEL vmlinuz
    APPEND initrd=initrd.img %s
`, cmdline)

	files := map[string]string{
		filepath.Join(root, "grub.cfg"):                       grub,
		filepath.Join(root, "grub", "grub.cfg"):               grub,
		filepath.Join(root, "grub", "x86_64-efi", "grub.cfg"): grub,
		filepath.Join(root, "pxelinux.cfg", "default"):        pxe,
	}
	for path, body := range files {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// dhcpRangeFor derives a DHCP pool from an interface address and mask.
func dhcpRangeFor(addr, mask string) (string, string, string, error) {
	ip := net.ParseIP(addr).To4()
	m := net.ParseIP(mask)
	if ip == nil || m == nil {
		return "", "", "", fmt.Errorf("invalid address %s/%s", addr, mask)
	}
	maskIP := net.IPMask(m.To4())
	ones, bits := maskIP.Size()
	hostBits := bits - ones
	if hostBits < 4 {
		return "", "", "", fmt.Errorf("subnet %s/%s is too small", addr, mask)
	}
	network := ip.Mask(maskIP)
	n := binaryUint32(network)
	size := uint32(1) << uint(hostBits)

	var start, end uint32
	if size >= 256 {
		start, end = n+100, n+199
	} else {
		start = n + size/2
		end = n + size - 3
	}
	if end <= start {
		return "", "", "", fmt.Errorf("subnet %s/%s is too small", addr, mask)
	}
	return uint32String(start), uint32String(end), mask, nil
}

func binaryUint32(ip net.IP) uint32 {
	ip = ip.To4()
	return uint32(ip[0])<<24 | uint32(ip[1])<<16 | uint32(ip[2])<<8 | uint32(ip[3])
}

func uint32String(v uint32) string {
	return fmt.Sprintf("%d.%d.%d.%d", byte(v>>24), byte(v>>16), byte(v>>8), byte(v))
}

// startDHCP writes the dnsmasq configuration and launches it.
func (s *Server) startDHCP(sess *Session) error {
	if !s.netboot {
		return fmt.Errorf("netboot assets are missing; rebuild the ISO")
	}
	root := filepath.Join(s.cfg.StateDir, "netboot")
	confPath := filepath.Join(s.cfg.StateDir, "dnsmasq.conf")

	var b strings.Builder
	b.WriteString("# generated by netclone\n")
	b.WriteString("port=0\n")
	b.WriteString("user=root\n")
	b.WriteString("group=root\n")
	b.WriteString("interface=" + sess.Iface + "\n")
	b.WriteString("bind-dynamic\n")
	b.WriteString("except-interface=lo\n")
	b.WriteString("dhcp-leasefile=" + filepath.Join(s.cfg.StateDir, "dnsmasq.leases") + "\n")
	b.WriteString("log-dhcp\n")
	b.WriteString("dhcp-no-override\n")

	switch sess.DHCPMode {
	case "proxy":
		ip := net.ParseIP(sess.ServerIP).To4()
		m := net.ParseIP(sess.Mask)
		if ip == nil || m == nil {
			return fmt.Errorf("invalid address %s/%s", sess.ServerIP, sess.Mask)
		}
		network := ip.Mask(net.IPMask(m.To4())).String()
		// proxyDHCP: only hand out boot information, IPs come from the
		// network's existing DHCP server.
		b.WriteString("dhcp-range=" + network + ",proxy\n")
	default:
		start, end, mask, err := dhcpRangeFor(sess.ServerIP, sess.Mask)
		if err != nil {
			return err
		}
		b.WriteString("dhcp-authoritative\n")
		b.WriteString("dhcp-range=" + start + "," + end + "," + mask + ",2h\n")
		b.WriteString("dhcp-option=option:router," + sess.ServerIP + "\n")
		b.WriteString("dhcp-option=option:dns-server," + sess.ServerIP + "\n")
	}

	b.WriteString("dhcp-match=set:efi64,option:client-arch,7\n")
	b.WriteString("dhcp-match=set:efi64,option:client-arch,9\n")
	b.WriteString("dhcp-boot=tag:efi64,grubnetx64.efi\n")
	b.WriteString("dhcp-boot=tag:!efi64,pxelinux.0\n")
	b.WriteString("enable-tftp\n")
	b.WriteString("tftp-root=" + root + "\n")
	b.WriteString("tftp-max=100\n")

	if err := os.WriteFile(confPath, []byte(b.String()), 0o644); err != nil {
		return err
	}
	if _, err := s.runCommand("dnsmasq", "dnsmasq", []string{
		"--no-daemon", "--conf-file=" + confPath, "--log-facility=-",
	}, nil); err != nil {
		return fmt.Errorf("cannot start dnsmasq: %w", err)
	}
	// Give dnsmasq a moment to bind ports 67/69, then make sure it is alive.
	time.Sleep(600 * time.Millisecond)
	s.mu.Lock()
	cmd, running := s.procs["dnsmasq"]
	s.mu.Unlock()
	if !running || (cmd.ProcessState != nil && cmd.ProcessState.Exited()) {
		return fmt.Errorf("dnsmasq failed to start; check that no other DHCP server uses interface %s", sess.Iface)
	}
	s.Logf("netboot: dnsmasq up on %s (%s mode, pool derived from %s)", sess.Iface, sess.DHCPMode, sess.ServerIP)
	return nil
}

func copyFile(src, dst string, mode os.FileMode) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	out, err := os.OpenFile(dst, os.O_CREATE|os.O_TRUNC|os.O_WRONLY, mode)
	if err != nil {
		return err
	}
	if _, err := io.Copy(out, in); err != nil {
		out.Close()
		os.Remove(dst)
		return err
	}
	return out.Close()
}
